"""Resumen de comentarios en PDF (como «Resumir comentarios» de Acrobat): por página, cada comentario o marca con
autor, fecha, estado, texto y respuestas, y opcionalmente la página en miniatura con las marcas."""
import html
import io
import pymupdf
from core.constants import APP_NAME

CSS = """
* {font-family: sans-serif; font-size: 9.5pt; line-height: 1.3;}
h1 {font-size: 18pt; color: #1F5FA8; margin-bottom: 2pt;}
h2 {font-size: 12.5pt; color: #1F5FA8; margin-top: 12pt; margin-bottom: 3pt;}
.sub {color: #666666;}
.item {margin-top: 5pt; margin-bottom: 3pt;}
.head {color: #444444; font-size: 8.5pt;}
.reply {margin-left: 14pt; color: #333333;}
img {margin-top: 3pt;}
"""

LABELS = {"es": {"title": "Resumen de comentarios", "page": "Página", "total": "{0} comentario(s) y marca(s)",
                 "made": "Generado por {0} el {1}", "none": "(sin texto)", "doc": "Documento:"},
          "en": {"title": "Comment summary", "page": "Page", "total": "{0} comment(s) and markup(s)",
                 "made": "Generated by {0} on {1}", "none": "(no text)", "doc": "Document:"}}


def build(items: list, out: str, doc_name: str, date: str, lang: str = "es", thumbs_doc=None) -> int:
    """`items`: [{page, kind, author, date, status, text, replies:[{author, date, text}]}] (ya traducidos).
    `thumbs_doc`: documento con las marcas exportadas para dibujar cada página en miniatura (o None).
    Escribe el PDF en `out` y devuelve el número de elementos."""
    L, e = LABELS.get(lang, LABELS["en"]), html.escape
    archive = pymupdf.Archive()
    parts = [f"<h1>{e(L['title'])}</h1>",
             f"<p class='sub'>{e(L['doc'])} {e(doc_name)}<br/>{e(L['total'].format(len(items)))}<br/>"
             f"{e(L['made'].format(APP_NAME, date))}</p>"]
    for pno in sorted({it["page"] for it in items}):
        parts.append(f"<h2>{e(L['page'])} {pno + 1}</h2>")
        if thumbs_doc is not None and pno < len(thumbs_doc):
            pix = thumbs_doc[pno].get_pixmap(dpi=40)
            name = f"p{pno}.png"
            archive.add(pix.tobytes("png"), name)
            parts.append(f"<img src='{name}' width='{min(pix.width, 200)}'/>")
        for it in (x for x in items if x["page"] == pno):
            head = " · ".join(x for x in (it["kind"], it.get("author", ""), it.get("date", ""), it.get("status", "")) if x)
            text = e(it.get("text") or L["none"]).replace("\n", "<br/>")
            reps = "".join(f"<div class='reply'>↳ <b>{e(r.get('author') or '—')}</b> {e(r.get('date', ''))}: "
                           f"{e(r.get('text', ''))}</div>" for r in it.get("replies", []))
            parts.append(f"<div class='item'><div class='head'><b>{e(head)}</b></div><div>{text}</div>{reps}</div>")
    story = pymupdf.Story(html="\n".join(parts), user_css=CSS, archive=archive)
    rect = pymupdf.paper_rect("a4"); body = rect + (50, 50, -50, -56)
    buf = io.BytesIO(); w = pymupdf.DocumentWriter(buf)
    more = True
    while more:
        dev = w.begin_page(rect); more, _ = story.place(body); story.draw(dev); w.end_page()
    w.close()
    d = pymupdf.open("pdf", buf.getvalue())
    for i, page in enumerate(d):
        page.insert_text((rect.width - 80, rect.height - 28), f"{i + 1} / {len(d)}", fontsize=8, color=(0.45, 0.45, 0.45))
    d.set_metadata({"title": f"{L['title']} — {doc_name}", "creator": APP_NAME, "producer": APP_NAME})
    d.save(out, garbage=3, deflate=True); d.close()
    return len(items)
